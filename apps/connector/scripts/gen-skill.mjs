import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../..', import.meta.url));
const skillDir = join(root, 'skills', 'twring');
const output = join(root, 'apps', 'connector', 'src', 'skill-files.ts');

async function filesUnder(dir) {
  const paths = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) paths.push(...(await filesUnder(path)));
    else if (entry.isFile()) paths.push(path);
  }
  return paths;
}

export async function generateSkill() {
  const paths = (await filesUnder(skillDir)).sort();
  const entries = await Promise.all(
    paths.map(async (path) => {
      const name = relative(skillDir, path).split(sep).join('/');
      const content = (await readFile(path, 'utf8')).replace(/\r/g, '');
      return `  { path: ${JSON.stringify(name)}, content: ${JSON.stringify(content)} },`;
    }),
  );
  const source = `// Generated by scripts/gen-skill.mjs from skills/twring. Do not edit; run \`pnpm --filter @twring/connector gen:skill\`.\nexport const SKILL_NAME = 'twring';\nexport const SKILL_FILES: readonly { path: string; content: string }[] = [\n${entries.join('\n')}\n];\n`;
  const current = await readFile(output, 'utf8').catch((error) => {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  });
  if (current !== source) await writeFile(output, source);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await generateSkill();
}
